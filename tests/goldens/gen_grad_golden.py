#!/usr/bin/env python3
"""Generate an INDEPENDENT numpy golden for reverse-mode gradients (docs/decisions.md Decision 14;
read by tests/unit/gradient_golden_test.cpp): HAND-DERIVED backprop formulas — deliberately no autograd
framework, so the golden stays independent and dependency-free. The golden STORES the inputs,
so there is no py<->C++ input-sync to keep aligned.

Cases:
  - MLP layer: loss = mean((relu(x@w + b) - t)^2); dW, dB, dX by hand chain rule.
  - conv1d (valid): loss = mean((correlate(x, w) - t)^2); dW (correlation with x),
    dX (full correlation with the flipped kernel — the overlap_add adjoint path).
  - softmax cross-entropy-ish composite: loss = mean((softmax(z, axis=1) - t)^2); dZ via the
    softmax Jacobian (verifies gradients() differentiates the composed softmax helper with no
    special rule).

Dev-only tool (numpy is not a build dependency). Run from the repo root:
    python3 tests/goldens/gen_grad_golden.py > tests/goldens/grad_golden.hpp
"""
import numpy as np

B, K, N = 4, 3, 2          # MLP layer extents
L, KW = 12, 3              # conv1d: signal length, kernel width
F = L - KW + 1             # valid frames
SB, SC = 4, 5              # softmax case extents


def flit(v):
    s = f"{v:.9g}"
    if not any(c in s for c in ".e"):
        s += ".0"
    return s + "f"


def carr(name, a):
    flat = np.asarray(a, dtype=np.float32).ravel()
    vals = ", ".join(flit(v) for v in flat)
    return f"inline constexpr std::array<float, {flat.size}> {name} = {{{vals}}};"


def main():
    rng_i = np.arange
    # deterministic, well-scaled inputs (no RNG — reproducible regeneration)
    x = (np.sin(0.7 * rng_i(B * K)) * 1.2).astype(np.float64).reshape(B, K)
    w = (np.cos(1.1 * rng_i(K * N)) * 0.8).astype(np.float64).reshape(K, N)
    bias = (np.sin(0.5 * rng_i(N)) * 0.3).astype(np.float64)
    t = (np.cos(0.9 * rng_i(B * N)) * 0.7).astype(np.float64).reshape(B, N)

    # --- MLP layer: y = relu(x@w + b); loss = mean((y - t)^2) ---
    z = x @ w + bias
    y = np.maximum(z, 0.0)
    d = (y - t) * (2.0 / (B * N))         # dL/dy
    dz = d * (z > 0)                      # relu mask (z == 0 -> subgradient 1 in Heinzel; z>0 strict
    dz_heinzel = d * (z >= 0)                  #   here both variants stored; inputs avoid exact 0)
    assert np.array_equal(dz, dz_heinzel), "inputs must not sit exactly on the relu kink"
    dW = x.T @ dz
    dB = dz.sum(axis=0)
    dX = dz @ w.T
    loss_mlp = np.mean((y - t) ** 2)

    # the SGD trajectory endpoint (lr 0.05, 100 steps — matched by the C++ training-loop test):
    # the relu model has an irreducible floor on this data, so the gate is "reaches numpy's
    # converged loss", not an arbitrary fraction of the initial loss.
    wt, bt = w.copy(), bias.copy()
    for _ in range(100):
        zt = x @ wt + bt
        yt = np.maximum(zt, 0.0)
        dzt = (yt - t) * (2.0 / (B * N)) * (zt > 0)
        wt -= 0.05 * (x.T @ dzt)
        bt -= 0.05 * dzt.sum(axis=0)
    loss_mlp_trained = np.mean((np.maximum(x @ wt + bt, 0.0) - t) ** 2)

    # --- conv1d (valid): y[f] = sum_k x[f+k] w[k]; loss = mean((y - tc)^2) ---
    xc = (np.sin(0.37 * rng_i(L)) * 1.5).astype(np.float64)
    wc = (np.cos(0.81 * rng_i(KW)) * 0.9).astype(np.float64)
    tc = (np.sin(1.3 * rng_i(F)) * 0.6).astype(np.float64)
    yc = np.array([np.dot(xc[f : f + KW], wc) for f in range(F)])
    dYc = (yc - tc) * (2.0 / F)
    dWc = np.array([np.dot(dYc, xc[k : k + F]) for k in range(KW)])
    dXc = np.zeros(L)
    for f in range(F):
        dXc[f : f + KW] += dYc[f] * wc
    loss_conv = np.mean((yc - tc) ** 2)

    # --- softmax composite: p = softmax(z, axis=1); loss = mean((p - ts)^2) ---
    zs = (np.sin(0.61 * rng_i(SB * SC)) * 1.7).astype(np.float64).reshape(SB, SC)
    ts = (np.cos(0.43 * rng_i(SB * SC)) * 0.5).astype(np.float64).reshape(SB, SC)
    e = np.exp(zs - zs.max(axis=1, keepdims=True))
    p = e / e.sum(axis=1, keepdims=True)
    dp = (p - ts) * (2.0 / (SB * SC))
    # softmax Jacobian: dz = p * (dp - sum(dp * p, axis))
    dZs = p * (dp - (dp * p).sum(axis=1, keepdims=True))
    loss_sm = np.mean((p - ts) ** 2)

    lines = [
        "#pragma once",
        "// AUTO-GENERATED by tests/goldens/gen_grad_golden.py — do not edit by hand.",
        "// INDEPENDENT numpy gradient goldens (hand-derived backprop formulas, float64 on the",
        "// numpy path — compared at tolerance; bit-exactness is a Heinzel-internal property).",
        "#include <array>",
        "",
        "namespace heinzel_golden::grad {",
        *(f"inline constexpr int {name} = {value};" for name, value in
          (("B", B), ("K", K), ("N", N), ("L", L), ("KW", KW), ("F", F), ("SB", SB), ("SC", SC))),
        carr("X", x),
        carr("W", w),
        carr("BIAS", bias),
        carr("T", t),
        f"inline constexpr float loss_mlp = {flit(loss_mlp)};",
        f"inline constexpr float loss_mlp_trained = {flit(loss_mlp_trained)};",
        carr("dW", dW),
        carr("dB", dB),
        carr("dX", dX),
        carr("XC", xc),
        carr("WC", wc),
        carr("TC", tc),
        f"inline constexpr float loss_conv = {flit(loss_conv)};",
        carr("dWC", dWc),
        carr("dXC", dXc),
        carr("ZS", zs),
        carr("TS", ts),
        f"inline constexpr float loss_softmax = {flit(loss_sm)};",
        carr("dZS", dZs),
        "} // namespace heinzel_golden::grad",
    ]
    print("\n".join(lines))


if __name__ == "__main__":
    main()
